// Shared dark theme for every Highcharts chart in pgPulse.
// Applied once with Highcharts.setOptions (see charts/highcharts.ts), so each
// chart only describes its own data and type.
import type { Options } from 'highcharts'
import { palette, seriesColors } from './palette'

const prefersReducedMotion =
  typeof window !== 'undefined' && window.matchMedia('(prefers-reduced-motion: reduce)').matches

const axisLabelStyle = { color: palette.textMuted, fontSize: '11px' }

export const highchartsTheme: Options = {
  colors: seriesColors,

  chart: {
    backgroundColor: 'transparent',
    style: { fontFamily: '"Inter Variable", ui-sans-serif, system-ui, sans-serif' },
    spacing: [8, 4, 4, 0],
    // Charts stay calm: short animations, none with reduced motion
    animation: prefersReducedMotion ? false : { duration: 300 },
  },

  // Show times in the viewer's own time zone (Highcharts defaults to UTC)
  time: { timezone: Intl.DateTimeFormat().resolvedOptions().timeZone },

  title: { text: undefined },
  subtitle: { text: undefined },
  credits: { enabled: false },
  exporting: { enabled: false },

  xAxis: {
    lineColor: palette.border,
    tickColor: palette.border,
    gridLineColor: palette.grid,
    labels: { style: axisLabelStyle },
    title: { style: axisLabelStyle },
  },

  yAxis: {
    gridLineColor: palette.grid,
    lineColor: palette.border,
    tickColor: palette.border,
    labels: { style: axisLabelStyle },
    title: { text: undefined, style: axisLabelStyle },
  },

  legend: {
    itemStyle: { color: palette.textMuted, fontWeight: '500', fontSize: '12px' },
    itemHoverStyle: { color: palette.text },
    itemHiddenStyle: { color: '#5b6370' },
  },

  tooltip: {
    backgroundColor: palette.popover,
    borderColor: palette.border,
    borderRadius: 8,
    shadow: false,
    style: { color: palette.text, fontSize: '12px' },
  },

  plotOptions: {
    series: {
      animation: prefersReducedMotion ? false : { duration: 400 },
      marker: { enabled: false, radius: 3 },
      states: { inactive: { opacity: 0.4 } },
    },
    pie: {
      borderColor: palette.card,
      borderWidth: 2,
      dataLabels: { style: { color: palette.textMuted, textOutline: 'none', fontWeight: '500' } },
    },
  },

  accessibility: {
    // Screen-reader summaries are generated by the accessibility module
    enabled: true,
  },
}
